# --- PDF CLINICAL REPORT GENERATION ---
class ClinicalReportPDF(FPDF):
    """Professional Clinical Report PDF Generator"""
    
    def __init__(self):
        super().__init__('P', 'mm', 'A4')
        self.accent_color = (0, 173, 181)  # Teal accent
        self.header_gray = (60, 60, 60)
        self.text_color = (30, 30, 30)
        self.light_gray = (180, 180, 180)
        
    def header(self):
        # ICU Guardian Logo/Title
        self.set_font('Helvetica', 'B', 18)
        self.set_text_color(*self.accent_color)
        self.cell(100, 10, 'ICU GUARDIAN', 0, 0, 'L')
        
        # Timestamp on right
        self.set_font('Helvetica', '', 10)
        self.set_text_color(*self.header_gray)
        timestamp = datetime.now().strftime('%Y-%m-%d %H:%M')
        self.cell(0, 10, f'Generated: {timestamp}', 0, 1, 'R')
        
        # Sub-header
        self.set_font('Helvetica', 'I', 10)
        self.set_text_color(*self.light_gray)
        self.cell(0, 6, 'Confidential Clinical Summary | Neuro-Trauma Unit', 0, 1, 'L')
        
        # Separator line
        self.set_draw_color(*self.accent_color)
        self.set_line_width(0.5)
        self.line(10, 28, 200, 28)
        self.ln(10)
        
    def footer(self):
        self.set_y(-35)
        
        # Signature line
        self.set_font('Helvetica', '', 10)
        self.set_text_color(*self.text_color)
        self.cell(130, 6, '', 0, 0)
        self.cell(0, 6, '__________________________', 0, 1, 'R')
        self.cell(130, 5, '', 0, 0)
        self.set_font('Helvetica', 'I', 9)
        self.set_text_color(*self.header_gray)
        self.cell(0, 5, 'Attending Physician / MD', 0, 1, 'R')
        
        # Legal disclaimer
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(*self.light_gray)
        self.cell(0, 5, 'Generated by ICU Guardian Clinical AI System. Not for legal diagnostic use.', 0, 1, 'C')
        
    def section_title(self, title):
        self.set_font('Helvetica', 'B', 12)
        self.set_text_color(*self.header_gray)
        self.set_fill_color(245, 245, 245)
        self.cell(0, 8, title, 0, 1, 'L', True)
        self.ln(3)
        
    def add_vitals_table(self, vitals_data):
        self.section_title('PATIENT VITALS SNAPSHOT')
        
        # Table header
        self.set_font('Helvetica', 'B', 10)
        self.set_text_color(255, 255, 255)
        self.set_fill_color(*self.header_gray)
        col_widths = [50, 45, 50, 45]
        headers = ['Parameter', 'Value', 'Parameter', 'Value']
        
        for i, (header, width) in enumerate(zip(headers, col_widths)):
            self.cell(width, 8, header, 1, 0, 'C', True)
        self.ln()
        
        # Table data
        self.set_font('Helvetica', '', 10)
        self.set_text_color(*self.text_color)
        self.set_fill_color(255, 255, 255)
        
        # Row 1: HR and SpO2
        self.cell(col_widths[0], 8, 'Average Heart Rate', 1, 0, 'L')
        self.cell(col_widths[1], 8, f"{vitals_data.get('hr', '--')} BPM", 1, 0, 'C')
        self.cell(col_widths[2], 8, 'Minimum SpO2', 1, 0, 'L')
        self.cell(col_widths[3], 8, f"{vitals_data.get('spo2', '--')}%", 1, 1, 'C')
        
        # Row 2: RASS and Risk
        self.cell(col_widths[0], 8, 'RASS Score', 1, 0, 'L')
        self.cell(col_widths[1], 8, str(vitals_data.get('rass', '--')), 1, 0, 'C')
        self.cell(col_widths[2], 8, 'AI Risk Probability', 1, 0, 'L')
        
        # Color code risk
        risk = vitals_data.get('risk', 0)
        if risk > 0.6:
            self.set_text_color(220, 53, 69)  # Red
        elif risk > 0.4:
            self.set_text_color(255, 152, 0)  # Orange
        else:
            self.set_text_color(40, 167, 69)  # Green
        self.cell(col_widths[3], 8, f"{risk:.0%}", 1, 1, 'C')
        self.set_text_color(*self.text_color)
        
        self.ln(5)
        
    def add_vitals_graph(self, hr_data, spo2_data):
        self.section_title('PHYSIOLOGICAL TREND ANALYSIS (Last 30 mins)')
        
        # Graph dimensions
        graph_x = 15
        graph_y = self.get_y() + 5
        graph_width = 180
        graph_height = 50
        
        # Draw graph background
        self.set_fill_color(250, 250, 250)
        self.set_draw_color(200, 200, 200)
        self.rect(graph_x, graph_y, graph_width, graph_height, 'DF')
        
        # Draw grid lines
        self.set_draw_color(230, 230, 230)
        for i in range(1, 5):
            y_line = graph_y + (graph_height / 5) * i
            self.line(graph_x, y_line, graph_x + graph_width, y_line)
        
        # Normalize data for plotting
        if len(hr_data) >= 2:
            hr_min, hr_max = min(hr_data), max(hr_data)
            if hr_max == hr_min:
                hr_max = hr_min + 1
            
            # Draw HR line (teal)
            self.set_draw_color(*self.accent_color)
            self.set_line_width(0.8)
            
            for i in range(len(hr_data) - 1):
                x1 = graph_x + (i / (len(hr_data) - 1)) * graph_width
                x2 = graph_x + ((i + 1) / (len(hr_data) - 1)) * graph_width
                y1 = graph_y + graph_height - ((hr_data[i] - hr_min) / (hr_max - hr_min)) * (graph_height - 10) - 5
                y2 = graph_y + graph_height - ((hr_data[i + 1] - hr_min) / (hr_max - hr_min)) * (graph_height - 10) - 5
                self.line(x1, y1, x2, y2)
        
        if len(spo2_data) >= 2:
            spo2_min, spo2_max = min(spo2_data), max(spo2_data)
            if spo2_max == spo2_min:
                spo2_max = spo2_min + 1
            
            # Draw SpO2 line (blue)
            self.set_draw_color(52, 152, 219)
            self.set_line_width(0.8)
            
            for i in range(len(spo2_data) - 1):
                x1 = graph_x + (i / (len(spo2_data) - 1)) * graph_width
                x2 = graph_x + ((i + 1) / (len(spo2_data) - 1)) * graph_width
                y1 = graph_y + graph_height - ((spo2_data[i] - spo2_min) / (spo2_max - spo2_min)) * (graph_height - 10) - 5
                y2 = graph_y + graph_height - ((spo2_data[i + 1] - spo2_min) / (spo2_max - spo2_min)) * (graph_height - 10) - 5
                self.line(x1, y1, x2, y2)
        
        # Legend
        self.set_y(graph_y + graph_height + 3)
        self.set_font('Helvetica', '', 8)
        self.set_text_color(*self.accent_color)
        self.cell(10, 5, '', 0, 0)
        self.cell(5, 5, '', 0, 0)
        self.set_draw_color(*self.accent_color)
        self.line(self.get_x(), self.get_y() + 2.5, self.get_x() + 15, self.get_y() + 2.5)
        self.cell(20, 5, '', 0, 0)
        self.set_text_color(*self.text_color)
        self.cell(30, 5, 'Heart Rate (BPM)', 0, 0, 'L')
        
        self.set_draw_color(52, 152, 219)
        self.line(self.get_x() + 5, self.get_y() + 2.5, self.get_x() + 20, self.get_y() + 2.5)
        self.cell(25, 5, '', 0, 0)
        self.set_text_color(52, 152, 219)
        self.cell(30, 5, 'SpO2 (%)', 0, 1, 'L')
        
        self.ln(8)
        
    def add_ai_observations(self, ai_message):
        self.section_title('AI CLINICAL OBSERVATIONS')
        
        self.set_font('Helvetica', '', 10)
        self.set_text_color(*self.text_color)
        self.multi_cell(0, 6, ai_message, 0, 'L')
        self.ln(5)
        
    def add_prescription_section(self):
        self.section_title('PHYSICIAN ORDERS / PRESCRIPTION')
        
        # Draw large bordered area with dotted lines
        box_x = 10
        box_y = self.get_y()
        box_width = 190
        box_height = 55
        
        self.set_draw_color(150, 150, 150)
        self.set_line_width(0.3)
        self.rect(box_x, box_y, box_width, box_height)
        
        # Draw dotted lines for writing
        self.set_draw_color(200, 200, 200)
        line_spacing = 9
        for i in range(1, 6):
            y_line = box_y + (line_spacing * i)
            # Draw dashed line
            x = box_x + 5
            while x < box_x + box_width - 5:
                self.line(x, y_line, min(x + 3, box_x + box_width - 5), y_line)
                x += 6
        
        self.set_y(box_y + box_height + 5)


def create_clinical_report_pdf(vitals_data, ai_message, hr_history, spo2_history):
    """Generate a professional clinical report PDF"""
    if not FPDF_AVAILABLE:
        return None
    
    pdf = ClinicalReportPDF()
    pdf.add_page()
    
    # Add vitals table
    pdf.add_vitals_table(vitals_data)
    
    # Add trend graph
    pdf.add_vitals_graph(hr_history, spo2_history)
    
    # Add AI observations
    pdf.add_ai_observations(ai_message)
    
    # Add prescription section
    pdf.add_prescription_section()
    
    # Return PDF as bytes
    return pdf.output(dest='S').encode('latin-1')

