# --- VISION SYSTEM CONTROL FUNCTIONS ---
def start_vision_system():
    """Launch the vision monitoring subprocess"""
    if st.session_state.vision_process is None or not is_vision_running():
        python_path = Path(sys.executable)
        script_path = Path("pillars/self_harm.py").resolve()
        
        import os
        env = os.environ.copy()
        env['PYTHONPATH'] = str(Path(__file__).parent.resolve())
        
        st.session_state.vision_process = subprocess.Popen(
            [str(python_path), str(script_path)],
            cwd=str(Path(__file__).parent),
            env=env,
            creationflags=subprocess.CREATE_NEW_CONSOLE if sys.platform == 'win32' else 0
        )
        add_alert("SYSTEM", "Vision Guardian activated", "success")
        return True
    return False

def stop_vision_system():
    """Terminate the vision monitoring subprocess"""
    if st.session_state.vision_process and is_vision_running():
        try:
            parent = psutil.Process(st.session_state.vision_process.pid)
            for child in parent.children(recursive=True):
                child.terminate()
            parent.terminate()
            parent.wait(timeout=5)
        except:
            pass
        st.session_state.vision_process = None
        add_alert("SYSTEM", "Vision Guardian deactivated", "info")
        return True
    return False

def is_vision_running():
    """Check if vision system process is active"""
    if st.session_state.vision_process:
        try:
            return psutil.pid_exists(st.session_state.vision_process.pid)
        except:
            return False
    return False

def add_alert(pillar, message, severity="warning"):
    """Add alert to history feed"""
    alert = {
        "timestamp": datetime.now().strftime("%H:%M:%S"),
        "pillar": pillar,
        "message": message,
        "severity": severity
    }
    st.session_state.alert_history.insert(0, alert)
    if len(st.session_state.alert_history) > 100:
        st.session_state.alert_history = st.session_state.alert_history[:100]

def update_pillar_status_from_file():
    """Read alert status from shared JSON file and update dashboard state"""
    try:
        if STATUS_FILE.exists():
            with open(STATUS_FILE, 'r') as f:
                data = json.load(f)
            
            if "pillars" in data:
                for pillar_name, pillar_data in data["pillars"].items():
                    if pillar_name in st.session_state.pillar_status:
                        # Update the pillar status
                        st.session_state.pillar_status[pillar_name]["active"] = pillar_data.get("active", False)
                        st.session_state.pillar_status[pillar_name]["count"] = pillar_data.get("count", 0)
                        
                        # Update last alert time if available
                        if pillar_data.get("last_alert"):
                            st.session_state.pillar_status[pillar_name]["last_alert"] = pillar_data["last_alert"]
                        
                        # Add to alert history if newly active
                        if pillar_data.get("active") and pillar_data.get("elapsed_seconds", 0) < 2:
                            elapsed = pillar_data.get("elapsed_seconds", 0)
                            add_alert(
                                pillar_name.upper(),
                                f"Alert detected - {elapsed:.1f}s elapsed",
                                "critical" if pillar_name in ["self_harm", "fall"] else "warning"
                            )
                
                return True
    except Exception as e:
        # Silently handle file read errors
        pass
    return False

